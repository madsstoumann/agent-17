#!/usr/bin/env node
/**
 * Builds everything that is a view of something else, so nobody writes it by hand:
 *   each file's `version` and `updated`, from the applied change records;
 *   memory/changelog/<file>.md and memory/CHANGELOG.md, from the same records;
 *   memory/decisions.md, from the records that hold a decision;
 *   INDEX.md, from the file headers.
 * `--check` writes nothing and exits 1 when a view is out of date.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { setMeta, list, cell } from './lib/md.mjs';
import { load, bumps, bump, args, LEVELS } from './lib/project.mjs';

const USAGE = 'Usage: build.mjs --root DIR [--check]';
const GENERATED = (name, description) => `---\nname: ${name}\ndescription: ${description}\nmetadata:\n  type: project\n  generated: true\n---\n\n<!-- Generated by the project skills from the change records and file headers. Do not edit. -->\n\n`;

export function build(root, { check = false } = {}) {
  const { base, files, changes, written } = load(root);
  const out = new Map();
  const problems = [];
  const applied = changes.filter((c) => c.meta.status === 'applied');

  // Versions and per-file history
  const state = new Map(written.map((f) => [f.key, { version: '0.1.0', updated: null, entries: [] }]));
  for (const c of applied) {
    for (const { file, level } of bumps(c.meta)) {
      if (!LEVELS.includes(level)) { problems.push(`${c.rel}: unknown bump level "${level}" for ${file}`); continue; }
      const s = state.get(file);
      if (!s) { problems.push(`${c.rel}: bumps "${file}", which is not a project file`); continue; }
      s.version = bump(s.version, level);
      s.updated = c.meta.date;
      s.entries.unshift({ version: s.version, date: c.meta.date, title: c.data.description, record: c });
    }
  }
  for (const f of written) {
    const s = state.get(f.key);
    let text = f.text;
    if (f.meta.version !== s.version) text = setMeta(text, 'version', s.version);
    if (s.updated && f.meta.updated !== s.updated) text = setMeta(text, 'updated', s.updated);
    if (text !== f.text) out.set(f.path, text);
    if (s.entries.length) {
      const up = path.relative(path.join(base, 'memory', 'changelog'), path.join(base, 'memory', 'changes')).split(path.sep).join('/');
      out.set(path.join(base, 'memory', 'changelog', `${f.key}.md`), GENERATED(`changelog-${f.key}`, `History of ${f.rel}, newest first`) + `# ${path.basename(f.rel)}\n\n` +
        s.entries.map((e) => `## ${e.version} - ${e.date}\n\n${e.title} ([change](${up}/${path.basename(e.record.rel)}))\n`).join('\n'));
    }
  }

  // Rollup
  if (applied.length) {
    out.set(path.join(base, 'memory', 'CHANGELOG.md'), GENERATED('changelog', 'Every applied change, newest first') + '# Changelog\n\n| Date | Change | Files |\n|---|---|---|\n' +
      [...applied].reverse().map((c) => `| ${c.meta.date} | [${cell(c.data.description)}](changes/${path.basename(c.rel)}) | ${bumps(c.meta).map((b) => `${b.file} (${b.level})`).join(', ')} |`).join('\n') + '\n');
  }

  // Decisions
  const decided = changes.filter((c) => c.meta.decision && c.meta.decision !== 'none' && c.meta.status !== 'rejected');
  const superseded = new Set(decided.flatMap((c) => list(c.meta.supersedes)));
  const line = (c) => `- ${c.meta.date} [${c.data.description}](changes/${path.basename(c.rel)})${list(c.meta.supersedes).length ? `, supersedes ${list(c.meta.supersedes).join(', ')}` : ''}`;
  const standing = decided.filter((c) => c.meta.decision === 'accepted' && !superseded.has(c.key));
  const open = decided.filter((c) => c.meta.decision === 'proposed');
  const past = decided.filter((c) => superseded.has(c.key) || c.meta.decision === 'superseded');
  const sect = (title, rows) => `## ${title}\n\n${rows.length ? [...rows].reverse().map(line).join('\n') : 'None.'}\n`;
  out.set(path.join(base, 'memory', 'decisions.md'), GENERATED('decisions', 'Standing and open decisions, one line each, with the reasoning in the change record') + '# Decisions\n\n' + [sect('Open', open), sect('Standing', standing), sect('Superseded', past)].join('\n'));

  // Index (from the headers as they will be after this build)
  const row = (f) => { const s = state.get(f.key); return `| [${f.rel.replace(/^project\//, '')}](${f.rel.replace(/^project\//, '')}) | ${cell(f.data.description)} | ${f.meta.owner ?? ''} | ${f.meta.audience ?? ''} | ${s.version} | ${f.meta.status ?? ''} | ${list(f.meta.open).length || ''} |`; };
  out.set(path.join(base, 'INDEX.md'), GENERATED('index', 'Every project file with what it holds, who is accountable, its version and what is still open') + '# Project files\n\nOpen only the files a task needs. `AGENTS.md` at the repo root holds the rules.\n\n| File | Holds | Owner | Audience | Version | Status | Open |\n|---|---|---|---|---|---|---|\n' + written.map(row).join('\n') + '\n\nKept by the skills: [memory/state.md](memory/state.md), [memory/decisions.md](memory/decisions.md)' + (applied.length ? ', [memory/CHANGELOG.md](memory/CHANGELOG.md)' : '') + '.\n');

  const stale = [...out].filter(([p, text]) => !fs.existsSync(p) || fs.readFileSync(p, 'utf8') !== text).map(([p]) => path.relative(root, p).split(path.sep).join('/'));
  if (!check && !problems.length) for (const [p, text] of out) { fs.mkdirSync(path.dirname(p), { recursive: true }); fs.writeFileSync(p, text); }
  return { root, problems, changed: stale, wrote: !check && !problems.length, files: files.length, changes: changes.length };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const a = args(process.argv.slice(2), { check: 'bool', help: 'bool' });
  if (a.help || !a.root) { console.log(USAGE); process.exit(a.help ? 0 : 2); }
  const r = build(path.resolve(a.root), { check: a.check });
  console.log(JSON.stringify(r, null, 2));
  process.exit(r.problems.length || (a.check && r.changed.length) ? 1 : 0);
}
